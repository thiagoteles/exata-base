import { type AccentPalette, type AccentReport, accentTokenNames } from "./accent";
import { css, hex, type PairReport, type Palette, type TokenName, tokenNames } from "./generate";
import type { Elevation } from "./preset-options";

export type RenderedAccent = { name: string; light: AccentPalette; dark: AccentPalette };

/* Turns generated palettes into the text of each file the generator owns. */

const SCRIM = "oklch(0% 0 0 / 0.5)";

const declarations = (palette: Palette, indent: string) =>
  tokenNames.map((name) => `${indent}--color-${name}: ${css(palette[name])};`).join("\n");

const accentDeclarations = (palette: AccentPalette, indent: string) =>
  accentTokenNames.map((name) => `${indent}--color-${name}: ${css(palette[name])};`).join("\n");

/*
 * Each accent redefines its four variables on its container. The dark rules carry the theme
 * selector in front, so they outrank the light rule on the same element, and a nested container
 * wins over its parent because its own declaration beats the inherited value.
 */
function renderAccentScopes(accents: readonly RenderedAccent[]): string {
  const scope = (name: string) => `[data-accent="${name}"]`;
  const rules = (selector: (name: string) => string, theme: "light" | "dark", indent: string) =>
    accents
      .map(
        (a) =>
          `${indent}${selector(a.name)} {\n${accentDeclarations(a[theme], `${indent}  `)}\n${indent}}`,
      )
      .join("\n\n");
  return `
@layer base {
${rules(scope, "light", "  ")}

${rules((name) => `:root[data-theme="dark"] ${scope(name)}`, "dark", "  ")}

  @media (prefers-color-scheme: dark) {
${rules((name) => `:root:not([data-theme="light"]) ${scope(name)}`, "dark", "    ")}
  }
}
`;
}

/** The brand comes first: it is the accent outside every scope and the way back to it inside one. */
export function renderTokensCss(
  light: Palette,
  dark: Palette,
  accents: readonly [RenderedAccent, ...RenderedAccent[]],
  elevation: Elevation,
): string {
  const [brand] = accents;
  const { rim, offset, blur, spread, opacity } = elevation;
  const lightShadow = `${rim} var(--color-line), 0 ${offset} ${blur} ${spread} ${css(light.ink, opacity)}`;
  const darkShadow = "0 0 0 1px var(--color-line-strong)";
  return `/*
 * Color tokens. Every color in the interface comes from this file.
 * Generated by \`pnpm tokens\` from design.json: do not edit by hand.
 */

@theme {
  --color-*: initial;

${declarations(light, "  ")}
${accentDeclarations(brand.light, "  ")}
  --color-scrim: ${SCRIM};

  --shadow-*: initial;
  --shadow-layer: ${lightShadow};
}

@layer base {
  :root {
    color-scheme: light;
  }

  :root[data-theme="dark"] {
    color-scheme: dark;
${declarations(dark, "    ")}
${accentDeclarations(brand.dark, "    ")}
    --shadow-layer: ${darkShadow};
  }

  @media (prefers-color-scheme: dark) {
    :root:not([data-theme="light"]) {
      color-scheme: dark;
${declarations(dark, "      ")}
${accentDeclarations(brand.dark, "      ")}
      --shadow-layer: ${darkShadow};
    }
  }
}
${renderAccentScopes(accents)}`;
}

const LINE_WIDTH = 100;

/** The accent names as a module, so code and the catalog know which scopes exist. */
export function renderAccentNames(names: readonly string[]): string {
  const quoted = names.map((name) => `"${name}"`);
  const inline = `export const accentNames = [${quoted.join(", ")}] as const;`;
  const list =
    inline.length <= LINE_WIDTH
      ? inline
      : `export const accentNames = [\n${quoted.map((q) => `  ${q},`).join("\n")}\n] as const;`;
  return `/*
 * The scoped accents a container can name with data-accent. Generated by \`pnpm tokens\` from
 * colors.json: do not edit by hand.
 */
${list}

export type AccentName = (typeof accentNames)[number];
`;
}

const emailKeys: ReadonlyArray<readonly [string, TokenName]> = [
  ["background", "background"],
  ["surface", "surface"],
  ["line", "line"],
  ["ink", "ink"],
  ["inkMuted", "ink-muted"],
  ["action", "action"],
  ["onAction", "on-action"],
  ["brandInk", "brand-ink"],
];

export function renderEmailPalette(light: Palette): string {
  const lines = emailKeys.map(([key, token]) => `  ${key}: "${hex(light[token])}",`).join("\n");
  return `/*
 * E-mail clients understand neither CSS variables nor oklch, so e-mails use these sRGB values of
 * the light theme tokens. Generated by \`pnpm tokens\` from design.json: do not edit by hand.
 */
export const emailPalette = {
${lines}
} as const;
`;
}

/** The light theme as the YAML lines of the DESIGN.md frontmatter. */
export function renderFrontmatterColors(light: Palette): string {
  return tokenNames.map((name) => `  ${name}: "${css(light[name])}"`).join("\n");
}

/*
 * One row per accent and theme, with the lowest ratio of each check, so the table stays short as
 * accents are added. The generator already refused anything below the minimum.
 */
function renderAccentTables(accents: readonly RenderedAccent[], report: readonly AccentReport[]) {
  const values = accents.flatMap((a) =>
    accentTokenNames.map(
      (token) =>
        `| ${a.name} | \`${token}\` | \`${css(a.light[token])}\` | \`${css(a.dark[token])}\` |`,
    ),
  );
  const lowest = (rows: readonly AccentReport[], foreground: string, against?: string) =>
    Math.min(
      ...rows
        .filter(
          (r) => r.foreground === foreground && (against === undefined || r.background === against),
        )
        .map((r) => r.ratio),
    ).toFixed(1);
  const checks = accents.flatMap((a) =>
    (["light", "dark"] as const).map((theme) => {
      const rows = report.filter((r) => r.accent === a.name && r.theme === theme);
      return `| ${a.name} | ${theme} | ${lowest(rows, "accent", "surface")}:1 | ${lowest(rows, "on-accent")}:1 | ${lowest(rows, "accent-ink")}:1 |`;
    }),
  );
  return `| Accent | Token | Light | Dark |
|--------|-------|-------|------|
${values.join("\n")}

| Accent | Theme | Fill on surface (3:1) | Text on fill (4.5:1) | Ink, lowest (4.5:1) |
|--------|-------|-----------------------|----------------------|---------------------|
${checks.join("\n")}`;
}

export function renderDesignTables(
  { light, dark, report }: { light: Palette; dark: Palette; report: readonly PairReport[] },
  scoped: { accents: readonly RenderedAccent[]; report: readonly AccentReport[] },
): string {
  const rows = tokenNames.map(
    (name) => `| \`${name}\` | \`${css(light[name])}\` | \`${css(dark[name])}\` |`,
  );
  const pairs = report
    .map(
      ({ theme, foreground, background, ratio, minimum }) =>
        `| ${theme} | \`${foreground}\` on \`${background}\` | ${ratio.toFixed(1)}:1 | ${minimum}:1 |`,
    )
    .join("\n");
  return `| Token | Light | Dark |
|-------|-------|------|
${rows.join("\n")}

| Theme | Pair | Measured | Needs |
|-------|------|----------|-------|
${pairs}

${renderAccentTables(scoped.accents, scoped.report)}`;
}

/** Replaces the text between two marker lines, keeping the markers. */
export function replaceBetween(text: string, start: string, end: string, body: string): string {
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from === -1 || to === -1 || to < from) {
    throw new Error(`Markers not found: ${start} ... ${end}`);
  }
  return `${text.slice(0, from + start.length)}\n${body}\n${text.slice(to)}`;
}

/** The chosen knobs and every variable they set, for the Preset section of DESIGN.md. */
export function renderPresetTables(
  choices: readonly [string, string][],
  variables: readonly [string, string][],
): string {
  const knobRows = choices.map(([knob, value]) => `| ${knob} | ${value} |`);
  const variableRows =
    variables.length === 0
      ? ["| (none) | the instrument values in this file apply unchanged |"]
      : variables.map(([name, value]) => `| \`${name}\` | \`${value}\` |`);
  return `| Knob | Choice |
|------|--------|
${knobRows.join("\n")}

| Variable the preset sets | Value |
|--------------------------|-------|
${variableRows.join("\n")}`;
}
